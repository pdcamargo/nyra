import { containersOf, isSlotRef, isUseNode, type Artboard, type AuthoredDocument, type Child, type DocNode, type VariantArtboard, type VariantInsert } from '../schema'
import { expandVariants } from '../variants'
import type { JsonObject, Migration } from './index'

/**
 * v2 → v3: artboards can be variants of another artboard (`extends`).
 *
 * The format change is additive, so this step could only move the number. It
 * does more, because the files that most need variants already exist: a
 * screen drawn in eight states is eight full copies, and every one of them is
 * read and written in full each time Claude touches the file. So existing
 * artboards that are near-copies of an earlier one are rewritten as variants
 * of it — the same picture, a fraction of the text.
 *
 * Nothing about what draws may change, so a conversion is kept only when its
 * expansion draws exactly the artboard it replaces. Anything that does not
 * round-trip stays as it was.
 *
 * Nodes are matched by id where the ids agree, and by shape where they do
 * not: files generated by a script often number each artboard's ids afresh
 * (`mf-b0`, `mub-b0`), so two copies of one screen share no ids at all. A
 * node matched by shape keeps the base's id once it is inherited — the one
 * thing a conversion changes. It is a handle, not something drawn, but an
 * open comment pinned to such a node falls back to its spot on the artboard.
 */

/** A variant has to be at most this share of the full artboard to be worth reading as one. */
const WORTH_IT = 0.5
/** How much shorter matching by shape has to be before it is worth renaming ids for. */
const PREFER_IDS = 0.8
/** Bases tried per artboard, most-shared ids first. Diffing every pair is quadratic in artboards. */
const CANDIDATES = 3

type Node = DocNode
type Changes = {
  replace: Record<string, Node>
  remove: string[]
  insert: VariantInsert[]
  set: Record<string, Record<string, unknown>>
}

const size = (v: unknown): number => JSON.stringify(v).length

/** Equal as JSON: same keys and values, in any key order. */
function same(a: unknown, b: unknown): boolean {
  if (a === b) return true
  if (typeof a !== 'object' || typeof b !== 'object' || a === null || b === null) return false
  if (Array.isArray(a) !== Array.isArray(b)) return false
  if (Array.isArray(a)) {
    const bb = b as unknown[]
    return a.length === bb.length && a.every((x, i) => same(x, bb[i]))
  }
  const ka = Object.keys(a)
  const kb = Object.keys(b)
  if (ka.length !== kb.length) return false
  return ka.every((k) => Object.hasOwn(b, k) && same((a as Record<string, unknown>)[k], (b as Record<string, unknown>)[k]))
}

const CONTAINER = new Set(['id', 'children', 'slots'])

/** Drop every node id, so two trees compare by what they draw. */
function anonymous(v: unknown): unknown {
  if (Array.isArray(v)) return v.map(anonymous)
  if (v === null || typeof v !== 'object') return v
  const out: Record<string, unknown> = {}
  for (const k of Object.keys(v).sort()) if (k !== 'id') out[k] = anonymous((v as Record<string, unknown>)[k])
  return out
}

const shapes = new WeakMap<object, string>()
/** A node's shape: everything under it but the ids, as a comparable string. */
function shape(n: Node): string {
  let s = shapes.get(n)
  if (s === undefined) {
    s = JSON.stringify(anonymous(n))
    shapes.set(n, s)
  }
  return s
}

/** Its own properties without the id or what it holds. */
const ownShapes = new WeakMap<object, string>()
const ownShape = (n: Node): string => {
  let s = ownShapes.get(n)
  if (s === undefined) {
    s = JSON.stringify(anonymous(shell(n)))
    ownShapes.set(n, s)
  }
  return s
}
const kind = (n: Node): string => (isUseNode(n) ? `use:${n.use}` : n.type)

/** A node without what it holds: what `set` can see and change. */
function shell(n: Node): Record<string, unknown> {
  const out: Record<string, unknown> = {}
  for (const [k, v] of Object.entries(n)) if (!CONTAINER.has(k)) out[k] = v
  return out
}

/**
 * The `set` that turns `b`'s own properties into `a`'s, or null when no set
 * can: a change of kind, or a value `set` reads as "delete" (`null`).
 */
function setFor(b: Node, a: Node): Record<string, unknown> | null {
  const sb = shell(b)
  const sa = shell(a)
  if (sb.type !== sa.type || sb.use !== sa.use) return null
  const out: Record<string, unknown> = {}
  for (const k of new Set([...Object.keys(sb), ...Object.keys(sa)])) {
    if (k === 'type' || k === 'use') continue
    if (!(k in sa)) {
      out[k] = null
      continue
    }
    if (sa[k] === null) return null
    if (same(sb[k], sa[k])) continue
    if (k === 'props' && isUseNode(a) && isUseNode(b) && b.props && a.props && Object.keys(a.props).length) {
      const pb = b.props
      const pa = a.props
      const props: Record<string, unknown> = {}
      for (const p of new Set([...Object.keys(pb), ...Object.keys(pa)])) {
        if (!(p in pa)) props[p] = null
        else if (pa[p] === null) return null
        else if (!same(pb[p], pa[p])) props[p] = pa[p]
      }
      out.props = props
      continue
    }
    if (k === 'props' && isUseNode(a) && !Object.keys(a.props ?? {}).length) return null
    out[k] = sa[k]
  }
  return out
}

/**
 * Pair `b`'s children with `a`'s: a longest common subsequence over "is the
 * same node" (same id, or same kind and own properties), then, between those
 * anchors, children of the same kind paired in order — the row whose label
 * changed. What is left over is removed from `b` or inserted from `a`.
 */
function align(bs: Node[], as: Node[], byShape: boolean): Map<number, number> {
  const alike = (x: Node, y: Node): boolean => x.id === y.id || (byShape && kind(x) === kind(y) && ownShape(x) === ownShape(y))
  const n = bs.length
  const m = as.length
  const t: number[][] = Array.from({ length: n + 1 }, () => new Array<number>(m + 1).fill(0))
  for (let i = n - 1; i >= 0; i--) {
    for (let j = m - 1; j >= 0; j--) t[i][j] = alike(bs[i], as[j]) ? t[i + 1][j + 1] + 1 : Math.max(t[i + 1][j], t[i][j + 1])
  }
  const anchors: [number, number][] = []
  let i = 0
  let j = 0
  while (i < n && j < m) {
    if (alike(bs[i], as[j])) anchors.push([i++, j++])
    else if (t[i + 1][j] >= t[i][j + 1]) i++
    else j++
  }
  const pairs = new Map<number, number>()
  let pb = 0
  let pa = 0
  for (const [bi, ai] of [...anchors, [n, m] as [number, number]]) {
    // The gap before this anchor: pair same-kind children in order.
    let x = pb
    for (let y = pa; byShape && y < ai && x < bi; y++) {
      if (kind(bs[x]) === kind(as[y])) pairs.set(x++, y)
    }
    if (bi < n) pairs.set(bi, ai)
    pb = bi + 1
    pa = ai + 1
  }
  return pairs
}

/** What a set of changes costs to write: the parts that say something. */
const cost = (ch: Changes): number =>
  (Object.keys(ch.replace).length ? size(ch.replace) : 0) +
  (ch.remove.length ? size(ch.remove) : 0) +
  (ch.insert.length ? size(ch.insert) : 0) +
  (Object.keys(ch.set).length ? size(ch.set) : 0)

const empty = (): Changes => ({ replace: {}, remove: [], insert: [], set: {} })

function merge(into: Changes, from: Changes): void {
  Object.assign(into.replace, from.replace)
  into.remove.push(...from.remove)
  into.insert.push(...from.insert)
  Object.assign(into.set, from.set)
}

const nodesOf = (items: Child[]): Node[] => items.filter((c): c is Node => !isSlotRef(c))

/**
 * What turns `b` into `a`: changes inside it, or replacing it whole when that
 * is shorter or the only way. `b` keeps its id either way it is inherited, so
 * every change is addressed by `b`'s ids.
 */
function diff(b: Node, a: Node, byShape: boolean): Changes {
  const whole = (): Changes => ({ ...empty(), replace: { [b.id]: a } })
  if (shape(b) === shape(a)) return empty()
  const own = setFor(b, a)
  const cb = containersOf(b)
  const ca = containersOf(a)
  // Containers have to line up: `insert` can add to one but never takes a key
  // away, and an artboard tree has no slot references to keep in place.
  if (
    own === null ||
    ('children' in b) !== ('children' in a) ||
    !same(cb.map((c) => c.slot), ca.map((c) => c.slot)) ||
    [...cb, ...ca].some((c) => c.items.some((x) => isSlotRef(x)))
  ) {
    return whole()
  }

  const out = empty()
  if (Object.keys(own).length) out.set[b.id] = own
  ca.forEach((box, n) => {
    const bs = nodesOf(cb[n].items)
    const as = nodesOf(box.items)
    const pairs = align(bs, as, byShape)
    const paired = new Map([...pairs].map(([bi, ai]) => [ai, bi]))
    bs.forEach((x, bi) => pairs.has(bi) || out.remove.push(x.id))
    // The id each of `a`'s children has once expanded: `b`'s for a paired
    // child, its own for an inserted one. Inserts anchor on these.
    const expandedId = as.map((x, ai) => (paired.has(ai) ? bs[paired.get(ai)!].id : x.id))
    as.forEach((x, ai) => {
      const bi = paired.get(ai)
      if (bi !== undefined) {
        merge(out, diff(bs[bi], x, byShape))
        return
      }
      if (ai > 0) out.insert.push({ after: expandedId[ai - 1], node: x })
      else {
        const next = as.findIndex((_, k) => k > 0 && paired.has(k))
        if (next > 0) out.insert.push({ before: expandedId[next], node: x })
        else out.insert.push(box.slot ? { into: b.id, slot: box.slot, node: x } : { into: b.id, node: x })
      }
    })
  })
  return cost(out) < size(a) ? out : whole()
}

/** `target` as a variant of `base`, or null when the artboard fields cannot follow it. */
function variantOf(base: Artboard, target: Artboard): VariantArtboard | null {
  // What a variant leaves off follows the base, and there is no "unset".
  for (const k of ['background', 'mode'] as const) if (target[k] === undefined && base[k] !== undefined) return null
  // By id where it is close: it keeps the artboard's own ids, and so leaves
  // later artboards that share them something to match. By shape only when
  // that is clearly shorter — it finds copies that renumbered, but every node
  // it pairs takes the base's id.
  const byId = diff(base.root, target.root, false)
  const byShape = diff(base.root, target.root, true)
  const ch = cost(byShape) < cost(byId) * PREFER_IDS ? byShape : byId
  if (Object.keys(ch.replace).includes(base.root.id)) return null
  const v: VariantArtboard = { id: target.id, name: target.name, extends: base.id }
  if (!same(target.size, base.size)) v.size = target.size
  if (target.background !== undefined && !same(target.background, base.background)) v.background = target.background
  if (target.position !== undefined) v.position = target.position
  if (target.mode !== undefined && target.mode !== base.mode) v.mode = target.mode
  if (Object.keys(ch.replace).length) v.replace = ch.replace
  if (ch.remove.length) v.remove = ch.remove
  if (ch.insert.length) v.insert = ch.insert
  if (Object.keys(ch.set).length) v.set = ch.set
  return v
}

/** The shapes of every subtree with something in it: how alike two artboards are. */
function shapeSet(n: Node, out = new Set<string>()): Set<string> {
  const kids = containersOf(n).flatMap((c) => nodesOf(c.items))
  if (kids.length) out.add(shape(n))
  for (const c of kids) shapeSet(c, out)
  out.add(`#${n.id}`)
  return out
}

const idSets = new WeakMap<object, Set<string>>()
function idsOf(n: Node): Set<string> {
  let s = idSets.get(n)
  if (!s) {
    s = new Set<string>()
    const walk = (x: Node): void => {
      s!.add(x.id)
      for (const c of containersOf(x)) nodesOf(c.items).forEach(walk)
    }
    walk(n)
    idSets.set(n, s)
  }
  return s
}

/** Two nodes in one tree with the same id: what an insert from `a` can cause. */
function duplicateIds(n: Node, seen = new Set<string>()): boolean {
  if (seen.has(n.id)) return true
  seen.add(n.id)
  return containersOf(n).some((c) => nodesOf(c.items).some((x) => duplicateIds(x, seen)))
}

/**
 * `v` expanded against `base`, when it draws exactly `target`; otherwise null.
 * The expansion is what later artboards must diff against: a base matched by
 * shape carries its own base's ids, not the ones it was written with.
 */
function drawnAs(base: Artboard, v: VariantArtboard, target: Artboard): Artboard | null {
  try {
    const doc = { schema: 3, name: 'check', theme: 'default', artboards: [base, v] } as AuthoredDocument
    const out = expandVariants(doc)
    if (out.issues.length > 0) return null
    const got = out.doc.artboards[1]
    const ok = !duplicateIds(got.root) && shape(got.root) === shape(target.root) && same({ ...got, root: null }, { ...target, root: null })
    return ok ? got : null
  } catch {
    return null
  }
}

/**
 * Rewrite near-copy artboards as variants. Bases are earlier artboards, so a
 * file still reads top to bottom; a base may itself become a variant, which
 * is safe because every conversion is checked against the original artboards.
 */
export function toVariants(artboards: Artboard[]): { artboards: (Artboard | VariantArtboard)[]; converted: number; saved: number } {
  const sets = artboards.map((a) => shapeSet(a.root))
  const out: (Artboard | VariantArtboard)[] = []
  /** Each artboard as the output will draw it, ids included. */
  const drawn: Artboard[] = []
  let converted = 0
  let saved = 0
  artboards.forEach((target, j) => {
    const full = size(target)
    // Two rankings, because either alone misses: shared ids find the copies
    // of a file that kept its ids, shared shapes the ones that renumbered.
    const overlap = (x: Set<string>, y: Set<string>): number => {
      let n = 0
      for (const k of x) if (y.has(k)) n++
      return n / Math.max(x.size, y.size)
    }
    const top = (score: (i: number) => number): number[] =>
      drawn
        .map((_, i) => ({ i, s: score(i) }))
        .filter((c) => c.s > 0)
        .sort((x, y) => y.s - x.s)
        .slice(0, CANDIDATES)
        .map((c) => c.i)
    const mine = idsOf(target.root)
    const candidates = [...new Set([...top((i) => overlap(sets[j], sets[i])), ...top((i) => overlap(mine, idsOf(drawn[i].root)))])].map((i) => ({ i }))
    let best: { v: VariantArtboard; drawn: Artboard } | null = null
    for (const { i } of candidates) {
      const v = variantOf(drawn[i], target)
      if (!v || (best && size(v) >= size(best.v))) continue
      const got = drawnAs(drawn[i], v, target)
      if (got) best = { v, drawn: got }
    }
    if (best && size(best.v) <= full * WORTH_IT) {
      out.push(best.v)
      drawn.push(best.drawn)
      converted++
      saved += full - size(best.v)
    } else {
      out.push(target)
      drawn.push(target)
    }
  })
  return { artboards: out, converted, saved }
}

export const variants: Migration = {
  from: 2,
  summary: 'artboards can be variants of another artboard',
  migrate: (doc, kind) => {
    if (kind !== 'design' || !Array.isArray(doc.artboards)) return { doc }
    const artboards = doc.artboards as unknown as Artboard[]
    // A file the current schema would refuse is left for validation to
    // explain; rewriting it first would only move the error somewhere else.
    if (!artboards.every((a) => a && typeof a === 'object' && a.root && typeof a.root === 'object' && typeof a.id === 'string')) {
      return { doc }
    }
    const r = toVariants(artboards)
    if (r.converted === 0) return { doc }
    const before = size(artboards)
    return {
      doc: { ...doc, artboards: r.artboards as unknown as JsonObject[] },
      notes: [
        `${r.converted} of ${artboards.length} artboards were near-copies of another and are now variants of it ("extends"); the file is ${Math.round((r.saved / before) * 100)}% shorter and draws the same.`
      ]
    }
  }
}
